class UserAddressForm(forms.ModelForm):
    state = forms.ChoiceField(
        choices=[("", "انتخاب استان...")] + IRAN_STATES,
        widget=forms.Select(attrs={'class': 'form-select', 'id': 'state-select'}),
        required=True,
        label="استان"
    )

    city = forms.ChoiceField(
        choices=[("", "ابتدا استان را انتخاب کنید...")],
        widget=forms.Select(attrs={'class': 'form-select', 'id': 'city-select'}),
        required=True,
        label="شهر"
    )

    class Meta:
        model = UserAddress
        fields = [
            "address",
            "state",
            "city",
            "zip_code",
            "is_default",
        ]
        widgets = {
            'address': forms.TextInput(attrs={'class': 'form-control', 'placeholder': 'خیابان، پلاک، واحد...'}),
            'zip_code': forms.TextInput(attrs={'class': 'form-control', 'placeholder': 'کد پستی', 'dir': 'ltr'}),
            'is_default': forms.CheckboxInput(attrs={'class': 'form-check-input'}),
        }

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        
        # ========== کلید اصلی برای حل مشکل ==========
        # اگر داده‌ای از POST وجود دارد، city choices را بر اساس state ارسالی پر کن
        if self.data and self.data.get('state'):
            state = self.data.get('state')
            cities = CITIES_BY_STATE.get(state, [])
            self.fields['city'].choices = [("", "انتخاب شهر...")] + [(city, city) for city in cities]
            # اگر city در داده‌ها وجود دارد، آن را به عنوان مقدار انتخاب شده نگه دار
            if self.data.get('city'):
                self.fields['city'].initial = self.data.get('city')
        
        # اگر نمونه‌ای وجود دارد و استان دارد، شهرهای آن استان را بارگذاری کن
        elif self.instance and self.instance.pk and self.instance.state:
            state = self.instance.state
            cities = CITIES_BY_STATE.get(state, [])
            self.fields['city'].choices = [("", "انتخاب شهر...")] + [(city, city) for city in cities]
            self.fields['city'].initial = self.instance.city